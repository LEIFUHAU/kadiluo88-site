var APP_I18N = { currentLang: "en" };

function applyLang(lang) {
  if (!I18N[lang]) lang = "en";
  APP_I18N.currentLang = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

  /* plain text nodes */
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var k = el.getAttribute("data-i18n");
    if (I18N[lang][k] != null) el.textContent = I18N[lang][k];
  });
  /* html nodes (contain <em> etc.) */
  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    var k = el.getAttribute("data-i18n-html");
    if (I18N[lang][k] != null) el.innerHTML = I18N[lang][k];
  });
  /* placeholders */
  document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    var k = el.getAttribute("data-i18n-ph");
    if (I18N[lang][k] != null) el.placeholder = I18N[lang][k];
  });

  /* batch: product cards */
  ["round", "square", "special"].forEach(function (id) {
    var sec = document.getElementById(id);
    if (!sec) return;
    var b = I18N_BATCH.cards[id];
    sec.querySelectorAll(".product-card").forEach(function (card) {
      var em = card.querySelector(".product-card__name em");
      if (em) em.textContent = b.name[lang];
      var sp = card.querySelector(".product-card__spec");
      if (sp) sp.textContent = b.spec[lang];
    });
  });

  /* batch: collapsible counts */
  document.querySelectorAll(".section--products").forEach(function (sec) {
    var n = sec.querySelectorAll(".product-card").length;
    var c = sec.querySelector(".cat-count");
    if (c) c.textContent = n + (lang === "zh" ? " 款" : " Models");
  });

  /* batch: selects */
  document.querySelectorAll("[data-i18n-opts]").forEach(function (sel) {
    var arr = I18N_BATCH[sel.getAttribute("data-i18n-opts")][lang];
    if (arr) Array.prototype.forEach.call(sel.options, function (o, i) {
      if (arr[i] != null) o.textContent = arr[i];
    });
  });

  /* batch: color swatches */
  var sw = document.querySelectorAll(".custom-colors .swatch span");
  I18N_BATCH.swatches[lang].forEach(function (txt, i) { if (sw[i]) sw[i].textContent = txt; });

  /* batch: technique list */
  var tech = document.querySelectorAll(".tech-list li");
  I18N_BATCH.tech[lang].forEach(function (pair, i) {
    if (!tech[i]) return;
    var span = tech[i].querySelector("span");
    var em = tech[i].querySelector("em");
    if (span) span.textContent = pair[0];
    if (em) em.textContent = pair[1];
  });

  /* batch: factory stat labels */
  var labels = document.querySelectorAll(".factory-stat__label");
  I18N_BATCH.facLabels[lang].forEach(function (html, i) { if (labels[i]) labels[i].innerHTML = html; });

  /* batch: faq */
  var faqs = document.querySelectorAll(".faq-item");
  I18N_BATCH.faq[lang].forEach(function (pair, i) {
    if (!faqs[i]) return;
    var q = faqs[i].querySelector(".faq-item__q span");
    var a = faqs[i].querySelector(".faq-item__a p");
    if (q) q.textContent = pair[0];
    if (a) a.textContent = pair[1];
  });

  /* toggle button label */
  var btn = document.getElementById("langToggle");
  if (btn) {
    btn.textContent = lang === "en" ? "中" : "EN";
    btn.setAttribute("aria-label", lang === "en" ? "切换到中文" : "Switch to English");
  }
}

function initI18n() {
  var saved = localStorage.getItem("catillo-lang") || "en";
  applyLang(saved);
  var btn = document.getElementById("langToggle");
  if (btn) {
    btn.addEventListener("click", function () {
      var next = APP_I18N.currentLang === "en" ? "zh" : "en";
      localStorage.setItem("catillo-lang", next);
      applyLang(next);
    });
  }
}
